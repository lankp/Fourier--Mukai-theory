#!/usr/bin/env python3
"""Write results/TODO.md: every numbered result of LP26 and GL26 that is not yet proved in
full generality, from results/COVERAGE.md.

    python3 scripts/todo.py

A row is a to-do unless its status is P (proved with the paper's hypotheses) or D (a
definition), and not qualified as abstract, categorical, affine or interface-only.  Rows
proved only in such a restricted form are listed separately: they still need the version
over algebraic spaces.  Order: LP26 before GL26 (maintainer, 26 November 2026); within a
paper, conditional results first (closest to done), then hypotheses, targets, absent.
"""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROW = re.compile(r'^\| ([A-Z][A-Za-z-]*(?: [A-Z]?[\d.]+[a-z]?)?) \| `([^`]+)` \| ([^|]*)\|(.*)$')
RANK = {'C': 0, 'H': 1, 'T': 2, '—': 3, '–': 3, '': 3}
RESTRICTED = ('abstract', '`Cat`', 'in Cat', 'affine', 'interface', 'one direction', 'module model')


def rows():
    paper = None
    for line in open(os.path.join(ROOT, 'results', 'COVERAGE.md'), encoding='utf8'):
        if line.startswith('## GL26'): paper = 'GL26'
        elif line.startswith('## LP26'): paper = 'LP26'
        elif line.startswith('## ') : paper = None if paper and not line.startswith('## ' + paper) else paper
        m = ROW.match(line)
        if paper and m:
            num, label, status, rest = m.group(1), m.group(2), m.group(3).strip(), m.group(4)
            yield paper, num, label, status, rest


def classify(status):
    code = status.split(' ')[0].strip('*') if status else ''
    restricted = any(k in status for k in RESTRICTED)
    if code in ('P', 'D') and not restricted:
        return None
    if code in ('P', 'D'):
        return 'restricted'
    return code


def main():
    todo = {'LP26': [], 'GL26': []}
    later = {'LP26': [], 'GL26': []}
    for paper, num, label, status, rest in rows():
        c = classify(status)
        if c is None: continue
        note = re.sub(r'\s+', ' ', rest.split('|')[0]).strip()[:160]
        entry = (num, label, status, note)
        if c == 'restricted': later[paper].append(entry)
        else: todo[paper].append((RANK.get(c, 3), entry))
    L = ['# To do', '',
         'Generated by `scripts/todo.py` from `results/COVERAGE.md`; do not edit by hand.',
         'Every numbered result not yet proved in full generality, over algebraic spaces and with',
         'nothing assumed but AxiomMath/Stacks.  Each wave takes its tasks from the top of this',
         'list (LP26 first, then GL26).  Status codes as in `COVERAGE.md`.', '']
    n = 0
    for paper in ('LP26', 'GL26'):
        items = [e for _, e in sorted(todo[paper], key=lambda x: x[0])]
        n += len(items) + len(later[paper])
        L += [f'## {paper}: not proved ({len(items)})', '',
              '| # | label | status | where / note |', '|---|---|---|---|']
        L += [f'| {a} | `{b}` | {c} | {d} |' for a, b, c, d in items] + ['']
        if later[paper]:
            L += [f'## {paper}: proved only in a restricted form ({len(later[paper])})', '',
                  'Proved abstractly, in `Cat`, affinely or over the interface; the version over',
                  'algebraic spaces is still to do.', '',
                  '| # | label | status | where / note |', '|---|---|---|---|']
            L += [f'| {a} | `{b}` | {c} | {d} |' for a, b, c, d in later[paper]] + ['']
    L.insert(6, f'**{n} items.**')
    L.insert(7, '')
    open(os.path.join(ROOT, 'results', 'TODO.md'), 'w', encoding='utf8').write('\n'.join(L))
    print(f'wrote results/TODO.md: {n} items')


if __name__ == '__main__':
    main()
