#!/usr/bin/env python3
"""Generate results/PROGRESS.md: a public, reproducible progress summary.

Everything is computed from files in the repository, so anyone can regenerate and
check it:
  * results/COVERAGE.md          per-result status of GL26 and LP26 (status codes P C H T D —)
  * results/statement-baseline.txt   the pinned headline declarations and their axioms
  * results/SWARM.md             the log of swarm tasks (one row per task)
  * the Lean sources              module and line counts, `sorry` occurrences

Usage:  python3 scripts/progress.py            (writes results/PROGRESS.md)
        python3 scripts/progress.py --check    (exit 1 if the file is out of date)
"""
import os, re, sys, subprocess, datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def rd(p): return open(os.path.join(ROOT, p), encoding='utf8').read()

CODES = ['P', 'C', 'H', 'T', 'D', '—']
NAMES = {'P': 'proved', 'C': 'proved, conditional on named inputs', 'H': 'interface field / hypothesis only',
         'T': 'stated as a target, not proved', 'D': 'definition or setup rendered', '—': 'absent'}
ROW = re.compile(r'^\| *((?:Thm|Theorem|Lem|Lemma|Prop|Proposition|Cor|Corollary|Def|Definition|Setup|Rem|Remark|Ex|Example|Question|Lem-Def|Lemma-Def)[^|]*)\|([^|]*)\|([^|]*)\|')

def coverage():
    s = rd('results/COVERAGE.md')
    gl = s[s.index('## GL26'):s.index('## LP26')]
    lp = s[s.index('## LP26'):]
    for stop in ('\n## Numbering', '\n## Verification'):
        if stop in lp: lp = lp[:lp.index(stop)]
    out = {}
    for name, part in (('GL26', gl), ('LP26', lp)):
        counts = {c: 0 for c in CODES}
        for line in part.split('\n'):
            m = ROW.match(line)
            if not m: continue
            code = m.group(3).strip().split(' ')[0].replace('–', '—') or '—'
            if code.startswith('Q') or m.group(1).strip().startswith('Question'): continue
            counts[code if code in counts else '—'] += 1
        out[name] = counts
    return out

def pinned():
    s = rd('results/statement-baseline.txt')
    if os.path.exists(os.path.join(ROOT, 'results/statement-baseline-spaces.txt')):
        s += '\n' + rd('results/statement-baseline-spaces.txt')
    decls = re.findall(r"^'([^']+)' depends on axioms: \[([^\]]*)\]", s, re.M)
    return [(d, ', '.join(a.strip() for a in ax.split(',') if a.strip())) for d, ax in decls]

def swarm_tasks():
    s = rd('results/SWARM.md')
    rows = [l for l in s.split('\n') if re.match(r'^\| *\d+b? *\| *`wave', l)]
    merged = [l for l in rows if re.search(r'\| *`[0-9a-f]{7}', l) or 'merge of' in l]
    waves = sorted({re.match(r'^\| *(\d+)', l).group(1) for l in rows}, key=int)
    return len(rows), len(merged), waves

def lean_stats():
    files = []
    for d in ('FourierMukai', 'WeakApprox', 'Spaces', 'SpacesVerified'):
        for dp, _, fs in os.walk(os.path.join(ROOT, d)):
            files += [os.path.join(dp, f) for f in fs if f.endswith('.lean')]
    lines = sum(sum(1 for _ in open(f, encoding='utf8')) for f in files)
    sorry_files = [os.path.relpath(f, ROOT) for f in files
                   if re.search(r'^\s*sorry\b|:= sorry|by sorry|\bsorry$', open(f, encoding='utf8').read(), re.M)]
    return len(files), lines, sorry_files

def render():
    cov = coverage(); dec = pinned(); ntask, nmerged, waves = swarm_tasks(); nfiles, nlines, sorry_files = lean_stats()
    std = {'propext', 'Classical.choice', 'Quot.sound'}
    clean = sum(1 for _, ax in dec if set(a.strip() for a in ax.split(',') if a.strip()) <= std)
    try: head = subprocess.check_output(['git', '-C', ROOT, 'rev-parse', '--short', 'HEAD'], text=True).strip()
    except Exception: head = 'unknown'
    L = ['# Progress', '',
         'Generated by `scripts/progress.py` from the repository itself '
         '(`results/COVERAGE.md`, `results/statement-baseline.txt`, `results/SWARM.md`, the Lean sources); '
         'regenerate with `python3 scripts/progress.py`.  Do not edit by hand.', '',
         f'Generated from commit `{head}`.', '',
         '## Numbered results of the two papers', '',
         'Status codes as defined in [`COVERAGE.md`](COVERAGE.md).  **P** counts a result proved in the '
         'form the tree states it, which for most GL26 results is a categorical, abstract or affine form; '
         'the goal is the papers\' full generality, over algebraic spaces, and `COVERAGE.md` says per row '
         'which form is proved.', '',
         '| paper | ' + ' | '.join(CODES) + ' | total |', '|---|' + '---:|' * (len(CODES) + 1)]
    for p in ('GL26', 'LP26'):
        c = cov[p]; L.append(f'| {p} | ' + ' | '.join(str(c[k]) for k in CODES) + f' | {sum(c.values())} |')
    L += ['', '| code | meaning |', '|---|---|'] + [f'| {k} | {NAMES[k]} |' for k in CODES]
    L += ['', '## Pinned headline declarations', '',
          f'{len(dec)} declarations are pinned in [`statement-baseline.txt`](statement-baseline.txt) and '
          f'[`statement-baseline-spaces.txt`](statement-baseline-spaces.txt) (the AxiomMath-based `Spaces` library) and re-checked '
          f'by `scripts/check_statements.sh` (`--spaces` for the second); {clean} of them depend only on `propext`, `Classical.choice`, '
          '`Quot.sound` (no `sorryAx`, no other axiom).', '',
          '| declaration | axioms |', '|---|---|']
    L += [f'| `{d}` | {ax.strip() or "none"} |' for d, ax in dec]
    L += ['', '## Work log', '',
          f'{ntask} swarm tasks in waves {", ".join(waves)} are logged in [`SWARM.md`](SWARM.md); '
          f'{nmerged} of them are merged into `formalization` after the orchestrator\'s seven-step verification '
          '(the others were stopped, deferred or are in progress; see the log).', '',
          '## Size and open `sorry`s', '',
          f'{nfiles} Lean modules, {nlines:,} lines (`FourierMukai/`, `WeakApprox/`, `Spaces/`, `SpacesVerified/`).  '
          f'Files containing `sorry`: {", ".join("`"+f+"`" for f in sorry_files) or "none"} '
          '(the deliberate specification targets; nothing proved depends on them).', '']
    return '\n'.join(L)

if __name__ == '__main__':
    out = os.path.join(ROOT, 'results', 'PROGRESS.md'); txt = render()
    if '--check' in sys.argv:
        cur = open(out, encoding='utf8').read() if os.path.exists(out) else ''
        strip = lambda t: re.sub(r'Generated from commit `[^`]*`', '', t)
        sys.exit(0 if strip(cur) == strip(txt) else 1)
    open(out, 'w', encoding='utf8').write(txt); print(f'wrote {os.path.relpath(out, ROOT)}')
